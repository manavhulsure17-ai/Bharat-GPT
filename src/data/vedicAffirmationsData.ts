/**
 * Returns today's default affirmation based on day of the year
 */
export function getDailyVedicAffirmation(date: Date = new Date()): VedicAffirmationItem {
  const startOfYear = new Date(date.getFullYear(), 0, 0);
  const diff = date.getTime() - startOfYear.getTime();
  const oneDay = 1000 * 60 * 60 * 24;
  const dayOfYear = Math.floor(diff / oneDay);
  const index = Math.abs(dayOfYear) % VEDIC_AFFIRMATIONS_COLLECTION.length;
  return VEDIC_AFFIRMATIONS_COLLECTION[index];
}
